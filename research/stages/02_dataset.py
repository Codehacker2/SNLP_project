def show_booklet(gt, max_pages=2, title=None, scale=0.42):
    pages = [cv2.imread(p, cv2.IMREAD_GRAYSCALE) for p in gt["page_paths"][:max_pages]]
    fig, axs = plt.subplots(1, len(pages), figsize=(5.2 * len(pages), 7.2))
