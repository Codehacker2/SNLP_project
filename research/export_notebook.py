def digest(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def safe_target(name: str) -> str:
    path = Path(name)
    if path.is_absolute() or path.drive or ".." in path.parts or "\\" in name:
        raise ValueError(f"Unexpected notebook file target: {name!r}")
    return path.as_posix()


def literal_file_bundles(source: str):
    """Expose string-embedded source files as readable snapshots, without eval/exec.

    The source dictionaries and their writing loops remain intact in the stages.
    This additionally makes _SMALL and _TESTS payloads readable as normal files.
    """
    for node in ast.parse(source).body:
        if not isinstance(node, ast.Assign):
            continue
        names = [target.id for target in node.targets if isinstance(target, ast.Name)]
        if not any(name in {"_SMALL", "_TESTS"} for name in names):
            continue
        payloads = ast.literal_eval(node.value)
        if not isinstance(payloads, dict) or not all(
            isinstance(key, str) and isinstance(value, str) for key, value in payloads.items()
        ):
            raise ValueError("Expected a literal filename-to-source dictionary")
        yield names[0], payloads


def build_export(notebook_path: Path = NOTEBOOK) -> dict[str, str]:
    notebook_bytes = notebook_path.read_bytes()
    notebook = json.loads(notebook_bytes)
    cells = notebook["cells"]
    outputs = {}
    manifest = {
        "notebook": "notebooks/snlp_group1_week7.ipynb",
        "notebook_sha256": hashlib.sha256(notebook_bytes).hexdigest(),
        "cell_numbering": "Zero-based, counting markdown and code cells",
        "stages": [],
        "cells": [],
    }
    covered = []
    for name, first, stop, description in STAGES:
        filename = f"stages/{name}.py"
        lines = [
            f'"""{description}.',
            "",
            "Generated by research/export_notebook.py; original statements are preserved.",
            "Run in notebook order using research/run.py to retain shared state.",
            '"""',
            "",
        ]
        manifest["stages"].append({"name": name, "file": filename, "description": description})
        for index in range(first, len(cells) if stop is None else stop):
            covered.append(index)
            cell = cells[index]
            source = "".join(cell.get("source", []))
            kind = cell["cell_type"]
            if kind not in {"code", "markdown"}:
                raise ValueError(f"Unsupported cell type {kind!r} at cell {index}")
            lines.append(f"# %% [{kind}] [notebook cell {index:03d}]")
            entry = {
                "cell": index,
                "type": kind,
                "file": filename,
                "start_line": len(lines) + 1,
                "source_sha256": digest(source),
            }
            if kind == "markdown":
                rendered = [f"# {line}" if line else "#" for line in source.splitlines()]
            elif source.startswith("%%writefile "):
                header, separator, body = source.partition("\n")
                args = shlex.split(header)
                if not separator or len(args) != 2:
                    raise ValueError(f"Unsupported writefile directive in cell {index}: {header}")
                target = safe_target(args[1])
                resource = f"file_cells/cell_{index:03d}/{target}"
                outputs[resource] = body
                rendered = [
                    f"# Original notebook directive: {header}",
                    f"_write_notebook_file({target!r}, {resource!r})",
                ]
                entry.update(target=target, resource=resource, payload_sha256=digest(body))
            else:
                # All ordinary Python statements stay exactly as written.
                rendered = source.splitlines()
                bundles = []
                for variable, payloads in literal_file_bundles(source):
                    for target, body in payloads.items():
                        target = safe_target(target)
                        resource = f"file_cells/cell_{index:03d}/{target}"
                        outputs[resource] = body
                        bundles.append({"variable": variable, "target": target,
                                        "resource": resource, "payload_sha256": digest(body)})
                if bundles:
                    entry["embedded_files"] = bundles
            lines.extend(rendered)
            entry["end_line"] = len(lines)
            manifest["cells"].append(entry)
            lines.append("")
        outputs[filename] = "\n".join(lines) + "\n"
    if covered != list(range(len(cells))):
        raise ValueError("Stage ranges must cover every notebook cell exactly once and in order")
    manifest["counts"] = {
        "cells": len(cells),
        "code_cells": sum(cell["cell_type"] == "code" for cell in cells),
        "writefile_cells": sum("resource" in entry for entry in manifest["cells"]),
        "embedded_files": sum(len(entry.get("embedded_files", [])) for entry in manifest["cells"]),
    }
    outputs["source_map.json"] = json.dumps(manifest, ensure_ascii=False, indent=2) + "\n"
    return outputs


def generated_paths() -> set[str]:
    paths = {"source_map.json"} if (RESEARCH / "source_map.json").is_file() else set()
    for directory in ("stages", "file_cells"):
        folder = RESEARCH / directory
        if folder.exists():
            paths.update(p.relative_to(RESEARCH).as_posix() for p in folder.rglob("*")
                         if p.is_file() and "__pycache__" not in p.parts)
    return paths


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify every generated file without writing")
    args = parser.parse_args(argv)
    outputs = build_export()
    if args.check:
        changed = [name for name, content in outputs.items()
                   if not (RESEARCH / name).is_file()
                   or (RESEARCH / name).read_text(encoding="utf-8") != content]
        stale = sorted(generated_paths() - outputs.keys())
        if changed or stale:
            print("Missing/changed files:\n" + "\n".join(changed))
            print("Unexpected generated files:\n" + "\n".join(stale))
            return 1
        manifest = json.loads(outputs["source_map.json"])
        print(f"Verified {len(outputs)} files; {manifest['counts']['code_cells']} code cells preserved.")
        return 0
    for name, content in outputs.items():
        path = RESEARCH / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
    print(f"Exported {len(outputs)} files into {RESEARCH}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
